    [TestMethod]
    public void ParseAllLayers_LothlorienKey_Returns80Layers()
    {
        var result = BannerLayerExpander.ParseAllLayers(LothlorienKey);

        Assert.AreEqual(80, result.Count);
    }

    [TestMethod]
    public void ParseAllLayers_RivendellKey_Returns29Layers()
