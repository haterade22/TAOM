    }

    [TestMethod]
    public void ParseAllLayers_EmptyString_ReturnsEmptyList()
    {
        var result = BannerLayerExpander.ParseAllLayers(string.Empty);

        Assert.AreEqual(0, result.Count);
    }

    [TestMethod]
    public void ParseAllLayers_NullString_ReturnsEmptyList()
    {
        var result = BannerLayerExpander.ParseAllLayers(null);

        Assert.AreEqual(0, result.Count);
    }

    [TestMethod]
    public void ParseAllLayers_InvalidString_ReturnsEmptyList()
    {
        var result = BannerLayerExpander.ParseAllLayers("not.a.valid.banner");

        Assert.AreEqual(0, result.Count);
    }

    [TestMethod]
    public void ParseAllLayers_LothlorienKey_FirstLayerMeshIdIs11()
    {
        var result = BannerLayerExpander.ParseAllLayers(LothlorienKey);

        Assert.AreEqual(11, result[0][0]);
    }

    [TestMethod]
    public void ParseAllLayers_EachLayerHas10Values()
    {
        var result = BannerLayerExpander.ParseAllLayers(LothlorienKey);

        foreach (var layer in result)
        {
            Assert.AreEqual(10, layer.Length);
        }
    }

    [TestMethod]
    public void ParseAllLayers_PartialChunk_IgnoresIncompleteTrailingValues()
    {
        var keyWithExtra = SimpleKey + ".999.888";

        var result = BannerLayerExpander.ParseAllLayers(keyWithExtra);

        Assert.AreEqual(5, result.Count);
    }
