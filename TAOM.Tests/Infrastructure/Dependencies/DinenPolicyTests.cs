using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.VisualStudio.TestTools.UnitTesting;
using TAOM.Dependencies.Foundation;

namespace TAOM.Tests.Infrastructure.Dependencies;

/// <summary>
/// The Modding Kit's message box answers (docs/features/dinen.md). Win32 values: MB_OK 0, MB_OKCANCEL 1,
/// MB_ABORTRETRYIGNORE 2, MB_YESNOCANCEL 3, MB_YESNO 4, MB_RETRYCANCEL 5, MB_CANCELTRYCONTINUE 6; IDOK 1, IDIGNORE 5,
/// IDYES 6, IDNO 7, IDCONTINUE 11, and 0 shows the box.
/// </summary>
[TestClass]
public class DinenPolicyTests
{
    [DataTestMethod]
    [DataRow("ASSERT", 2u, 5)]
    [DataRow("SAFE ASSERT", 2u, 5)]
    [DataRow(" ASSERT ", 0x12u, 5)]
    [DataRow("RGL CONTENT WARNING", 0u, 1)]
    [DataRow("RGL CONTENT ERROR", 1u, 1)]
    [DataRow("rgl warning", 0u, 1)]
    [DataRow("Safe Mode", 4u, 7)]
    [DataRow("Safe Mode", 3u, 7)]
    [DataRow("*_*", 4u, 7)]
    [DataRow("Always Ignore?", 4u, 6)]
    [DataRow("Always Ignore?", 3u, 6)]
    [DataRow("ASSERT", 6u, 11)]
    [DataRow("ASSERT", 0x52012u, 5)]
    [DataRow("SAFE ASSERT", 0x52012u, 5)]
    [DataRow("RGL CONTENT WARNING", 0x41030u, 1)]
    [DataRow("RGL WARNING", 0x41030u, 1)]
    [DataRow("Safe Mode", 0x40004u, 7)]
    [DataRow("*_*", 0x40004u, 7)]
    [DataRow("Always Ignore?", 0x40001u, 1)]
    public void AnswerFor_KnownCaption_ReturnsTheHarmlessButton(string caption, uint style, int expected)
    {
        Assert.AreEqual(expected, DinenPolicy.AnswerFor(caption, style));
    }

    [DataTestMethod]
    [DataRow("Save changes?", 4u)]
    [DataRow("Error", 0u)]
    [DataRow("", 0u)]
    [DataRow(null, 0u)]
    [DataRow("ASSERT", 5u)]
    [DataRow("ASSERT", 7u)]
    public void AnswerFor_OtherCaptionOrNoHarmlessButton_ShowsTheBox(string? caption, uint style)
    {
        Assert.AreEqual(0, DinenPolicy.AnswerFor(caption, style));
    }

    [TestMethod]
    public void AnswerFor_NeverAnswersAbortOrRetry()
    {
        var forbidden = new HashSet<int> { 3, 4, 10 };
        foreach (var caption in new[] { "ASSERT", "SAFE ASSERT", "RGL WARNING", "Safe Mode", "Always Ignore?", "*_*" })
            for (uint style = 0; style < 16; style++)
                Assert.IsFalse(forbidden.Contains(DinenPolicy.AnswerFor(caption, style)), $"{caption} style {style}");
    }

    [TestMethod]
    public void FindImportSlots_ReturnsTheIatSlotOfEachNamedFunction()
    {
        var image = new FakeImage();
        var slots = DinenPolicy.FindImportSlots(image.ReadInt32, image.ReadInt64, image.ReadAnsi, "user32.dll", "MessageBoxA");

        CollectionAssert.AreEqual(new[] { FakeImage.User32Iat + 8 }, new List<int>(slots));
    }

    [TestMethod]
    public void FindImportSlots_OtherDllOrMissingFunction_ReturnsNone()
    {
        var image = new FakeImage();

        Assert.AreEqual(0, DinenPolicy.FindImportSlots(image.ReadInt32, image.ReadInt64, image.ReadAnsi, "gdi32.dll", "MessageBoxA").Count);
        Assert.AreEqual(0, DinenPolicy.FindImportSlots(image.ReadInt32, image.ReadInt64, image.ReadAnsi, "user32.dll", "MessageBoxW").Count);
    }

    [TestMethod]
    public void FindImportSlots_NoLookupTable_SkipsTheDescriptorWithoutReadingResolvedAddresses()
    {
        var image = new FakeImage(withNameTable: false);
        var slots = DinenPolicy.FindImportSlots(image.ReadInt32, image.ReadInt64, image.ReadAnsi, "USER32.dll", "MessageBoxA");

        Assert.AreEqual(0, slots.Count);
    }

    [TestMethod]
    [TestCategory("BindingVerification")]
    public void ActionCodeTarget_BindsOnTheInstalledEngine_WithThePrefixShape()
    {
        System.Reflection.Assembly assembly;
        try { assembly = System.Reflection.Assembly.Load("TaleWorlds.MountAndBlade.AutoGenerated"); }
        catch (Exception ex) { Assert.Inconclusive($"TaleWorlds.MountAndBlade.AutoGenerated not loadable: {ex.GetType().Name}"); return; }
        var type = assembly.GetType("ManagedCallbacks.ScriptingInterfaceOfIMBAnimation");
        Assert.IsNotNull(type, "Dinen.cs patches ManagedCallbacks.ScriptingInterfaceOfIMBAnimation by name");

        var target = type!.GetMethod("GetActionCodeWithName", new[] { typeof(string) });
        var count = type.GetMethod("GetNumActionCodes", Type.EmptyTypes);
        Assert.IsNotNull(target);
        Assert.AreEqual(typeof(int), target!.ReturnType);
        Assert.AreEqual("name", target.GetParameters()[0].Name);
        Assert.IsNotNull(count);
        Assert.AreEqual(typeof(int), count!.ReturnType);
        var prefix = typeof(Dinen).GetMethod("ActionCodePrefix", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Static)!;
        CollectionAssert.AreEqual(new[] { "__instance", "name", "__result" }, prefix.GetParameters().Select(p => p.Name).ToArray());
    }

    [DataTestMethod]
    [DataRow(nameof(TaleWorlds.Library.Debug.FailedAssert), "FailedAssertPrefix", new[] { "message", "callerFile", "callerMethod", "callerLine" })]
    [DataRow(nameof(TaleWorlds.Library.Debug.Assert), "AssertPrefix", new[] { "condition", "message", "callerFile", "callerMethod", "callerLine" })]
    public void AssertPrefixes_ParameterNames_MatchTheTarget(string targetName, string prefixName, string[] expected)
    {
        static string[] Names(System.Reflection.MethodInfo method) => method.GetParameters().Select(p => p.Name!).ToArray();
        var target = typeof(TaleWorlds.Library.Debug).GetMethod(targetName)!;
        var prefix = typeof(Dinen).GetMethod(prefixName, System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Static)!;

        CollectionAssert.AreEqual(expected, Names(target));
        CollectionAssert.AreEqual(Names(target), Names(prefix));
    }

    /// <summary>
    /// A PE32+ image as it lies in memory: kernel32 first, then user32 with an ordinal, GetDC and MessageBoxA. Without a
    /// lookup table, the user32 address table holds resolved addresses, as the loader leaves it.
    /// </summary>
    private sealed class FakeImage
    {
        public const int User32Iat = 0x600;
        private const int Kernel32Iat = 0x500;
        private readonly byte[] _bytes = new byte[0x1000];

        public FakeImage(bool withNameTable = true)
        {
            Int32(0x3C, 0x80);
            Int32(0x80 + 24 + 112 + 8, 0x200);
            Descriptor(0x200, withNameTable ? 0x400 : 0, 0x300, Kernel32Iat);
            Descriptor(0x214, withNameTable ? 0x420 : 0, 0x310, User32Iat);
            Ansi(0x300, "KERNEL32.dll");
            Ansi(0x310, "USER32.dll");
            Ansi(0x702, "MessageBoxA");
            Ansi(0x722, "GetDC");
            Ansi(0x742, "ExitProcess");
            Thunks(withNameTable ? 0x400 : Kernel32Iat, 0x740);
            Thunks(Kernel32Iat, 0x740);
            if (withNameTable)
            {
                Thunks(0x420, unchecked((long)0x8000000000000010UL), 0x700, 0x720);
                Thunks(User32Iat, 0x11111111, 0x22222222, 0x33333333);
            }
            else
            {
                Thunks(User32Iat, 0x00007FF912345678, 0x00007FF912345690, 0x00007FF9123456A8);
            }
        }

        public int ReadInt32(int offset) => BitConverter.ToInt32(_bytes, offset);

        public long ReadInt64(int offset) => BitConverter.ToInt64(_bytes, offset);

        public string ReadAnsi(int offset)
        {
            var end = Array.IndexOf(_bytes, (byte)0, offset);
            return Encoding.ASCII.GetString(_bytes, offset, end - offset);
        }

        private void Descriptor(int at, int nameTable, int name, int iat)
        {
            Int32(at, nameTable);
            Int32(at + 12, name);
            Int32(at + 16, iat);
        }

        private void Thunks(int at, params long[] values)
        {
            for (var i = 0; i < values.Length; i++)
                BitConverter.GetBytes(values[i]).CopyTo(_bytes, at + i * 8);
        }

        private void Int32(int at, int value) => BitConverter.GetBytes(value).CopyTo(_bytes, at);

        private void Ansi(int at, string text) => Encoding.ASCII.GetBytes(text).CopyTo(_bytes, at);
    }
}
