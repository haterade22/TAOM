#!/usr/bin/env python3
"""Turn the writers' incident drafts (TSV) into the English game-text rows Incident Voices reads.

Draft columns: key, incident_id, side, slot, text, notes. A row is one text:
  key       taom_inc_<incident id without incident_>_<all|free|shadow>_<title|desc|optN>
            taom_inc_voc_<free|shadow>_<word>          (side vocabulary, incident_id "voc")
            taom_inc_voc_<people>[_<free|shadow>]_<word>   (a people's own word, tried before the side's; people:
                                                       isengard, west, rohirrim, northmen, dunlendings, southrons,
                                                       easterlings, elves, dwarves, orcs; side column = the part
                                                       between voc_ and the word)
  side      all (one text for everyone), free or shadow; slot "-" is a note row (no text) and is skipped.

Each text becomes  <string id="str_taom_inc.<variation>" text="{=<key>}<text>" />  inside one generated block of an
existing English strings file (default taom_encounter_strings.xml, already registered as a GameText source), between the
markers below. The block is rewritten whole on every --apply, so the drafts folder (docs/features/incident-voices/drafts/,
committed) is the source of truth; a test fails when the shipped block and the drafts differ. An --apply that would drop a
shipped row stops unless --allow-remove is given. The 12 language files are the project lead's pass (the localize skill):
this tool never touches them.

Validation (all errors are listed, nothing is written while there is one):
  - the key matches incident, side and slot; the incident is in incidents_lotr.json and has that side's version
  - the slot exists (optN no higher than the vanilla option count); an incident with "vanilla_text" takes no text
  - every {VARIABLE} is one vanilla's condition sets for that incident (the catalog's "vars") or a vocabulary word
  - a text that uses a vocabulary word needs that word's free and shadow rows in the same run
  - no em or en dash, none of the Calradian words the plan bans, no tab, newline or empty text, no repeated key

Usage (no file named: every *.tsv in the drafts folder):
  python tools/incidents_drafts_to_xml.py [<drafts.tsv>...]                    check only, print a summary
  python tools/incidents_drafts_to_xml.py --apply [<drafts.tsv>...]            also rewrite the block in the XML file
  python tools/incidents_drafts_to_xml.py --apply --allow-remove [<drafts>]    and let it drop rows the drafts no longer hold
Exit codes: 0 done, 1 problems found or the write refused, 2 a missing file or a broken marker.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from pathlib import Path
from xml.etree import ElementTree

REPO = Path(__file__).resolve().parents[1]
MODULE_DATA = REPO / "Main" / "_Module" / "ModuleData"
DEFAULT_CATALOG = MODULE_DATA / "incidents_lotr" / "incidents_lotr.json"
DEFAULT_XML = MODULE_DATA / "taom_encounter_strings.xml"
DEFAULT_DRAFTS = REPO / "docs" / "features" / "incident-voices" / "drafts"

KEY_PREFIX = "taom_inc_"
GAME_TEXT_ID = "str_taom_inc"
BEGIN_PREFIX = "<!-- INCIDENT-VOICES-BEGIN"
END_PREFIX = "<!-- INCIDENT-VOICES-END"
BEGIN = BEGIN_PREFIX + ": generated by tools/incidents_drafts_to_xml.py from the drafts in docs/features/incident-voices/drafts; do not edit by hand -->"
END = END_PREFIX + " -->"
ROW_ID = re.compile(r'<string id="(' + GAME_TEXT_ID + r'\.[^"]+)"')
COLUMNS = ["key", "incident_id", "side", "slot", "text", "notes"]
SIDES = ("all", "free", "shadow")
VOCAB_SIDES = ("free", "shadow")
VOCAB_PEOPLES = ("isengard", "west", "rohirrim", "northmen", "dunlendings", "southrons", "easterlings", "elves", "dwarves", "orcs")
VOCAB_SCOPE = re.compile(r"^(free|shadow|(" + "|".join(VOCAB_PEOPLES) + r")(_(free|shadow))?)$")
FORBIDDEN_WORDS = ("calradia", "calradian", "calradic", "heaven", "empire", "imperial")
VARIABLE = re.compile(r"\{([^{}]*)\}")
SLOT = re.compile(r"^(title|desc|opt([1-9][0-9]*))$")
DASHES = (chr(0x2013), chr(0x2014))


def load_catalog(path: Path) -> dict:
    """The catalog as {"vocabulary": [...], "incidents": {short id: row}}."""
    data = json.loads(path.read_text(encoding="utf-8"))
    rows = {}
    for row in data["incidents"]:
        short = row["id"][len("incident_"):] if row["id"].startswith("incident_") else row["id"]
        rows[short] = row
    return {"vocabulary": [w.upper() for w in data.get("vocabulary", [])], "incidents": rows}


def read_drafts(paths: list[Path]) -> list[dict]:
    """Every row of every file, with the file and line it came from."""
    rows = []
    for path in paths:
        with path.open(encoding="utf-8-sig", newline="") as handle:
            reader = csv.reader(handle, delimiter="\t", quoting=csv.QUOTE_NONE)
            header = next(reader, None)
            if header is None or [h.strip() for h in header[: len(COLUMNS)]] != COLUMNS:
                raise ValueError(f"{path}: the header must be {COLUMNS}, got {header}")
            for number, cells in enumerate(reader, start=2):
                if not any(cell.strip() for cell in cells):
                    continue
                if len(cells) > len(COLUMNS):
                    raise ValueError(f"{path.name}:{number}: {len(cells)} cells for {len(COLUMNS)} columns (a tab inside the text?)")
                cells = cells + [""] * (len(COLUMNS) - len(cells))
                row = {name: value.strip() for name, value in zip(COLUMNS, cells)}
                row["where"] = f"{path.name}:{number}"
                rows.append(row)
    return rows


def variables_in(text: str) -> list[str]:
    """The plain {VARIABLE} names of a text. Tags the engine reads ({=key}, {?X}, {\\?}, {.link}) are not variables."""
    names = []
    for content in VARIABLE.findall(text):
        if not content or content[0] in "?\\=.%!*@^":
            continue
        names.append(content.split(".")[0])
    return names


def validate(rows: list[dict], catalog: dict) -> list[str]:
    """Every problem found, as one line each."""
    errors: list[str] = []
    seen: dict[str, str] = {}
    vocabulary = set(catalog["vocabulary"])
    vocab_have: set[tuple[str, str]] = set()
    vocab_used: list[tuple[str, str]] = []

    for row in rows:
        where, key, side, slot, text = row["where"], row["key"], row["side"], row["slot"], row["text"]
        if slot == "-":
            continue
        is_vocab = key.startswith(KEY_PREFIX + "voc_")
        if key in seen:
            errors.append(f"{where}: key {key} is repeated (first at {seen[key]})")
        seen[key] = where

        if not text:
            errors.append(f"{where}: {key} has no text")
            continue
        if "\t" in text or "\n" in text or "\r" in text:
            errors.append(f"{where}: {key} holds a tab or a line break")
        if any(d in text for d in DASHES):
            errors.append(f"{where}: {key} holds an em or en dash")
        lowered = text.lower()
        for word in FORBIDDEN_WORDS:
            if re.search(r"\b" + word + r"\b", lowered):
                errors.append(f"{where}: {key} uses the banned word '{word}'")

        if is_vocab:
            if not VOCAB_SCOPE.match(side) or row["incident_id"].lower() not in ("voc", "vocabulary", ""):
                errors.append(f"{where}: {key} is a vocabulary row, so its side must be free, shadow or a people (optionally _free or _shadow) and its incident_id voc")
                continue
            word = slot.upper()
            if word not in vocabulary:
                errors.append(f"{where}: {key}: '{slot}' is not a vocabulary word ({', '.join(sorted(vocabulary))})")
                continue
            expected = f"{KEY_PREFIX}voc_{side}_{slot.lower()}"
            if key != expected:
                errors.append(f"{where}: key {key} should be {expected}")
            if side in VOCAB_SIDES:
                vocab_have.add((side, word))
            for name in variables_in(text):
                errors.append(f"{where}: {key} is a vocabulary text and must not hold the variable {{{name}}}")
            continue

        incident_id = row["incident_id"]
        short = incident_id[len("incident_"):] if incident_id.startswith("incident_") else incident_id
        entry = catalog["incidents"].get(short)
        if entry is None:
            errors.append(f"{where}: {key}: incident '{incident_id}' is not in the catalog")
            continue
        expected = f"{KEY_PREFIX}{short}_{side}_{slot}"
        if key != expected:
            errors.append(f"{where}: key {key} should be {expected}")
        if side not in SIDES or side not in entry["versions"]:
            errors.append(f"{where}: {key}: {incident_id} has the versions {entry['versions']}, not '{side}'")
        if entry.get("vanilla_text"):
            errors.append(f"{where}: {key}: {incident_id} keeps another developer's text; write none")
        match = SLOT.match(slot)
        if not match:
            errors.append(f"{where}: {key}: slot '{slot}' is not title, desc or optN")
        elif match.group(2) and int(match.group(2)) > entry["options"]:
            errors.append(f"{where}: {key}: {incident_id} has {entry['options']} options, so {slot} does not exist")

        allowed = {v.upper() for v in entry.get("vars", [])} | vocabulary
        for name in variables_in(text):
            if name not in allowed:
                errors.append(f"{where}: {key} uses {{{name}}}, which is neither one of vanilla's variables for {incident_id} nor a vocabulary word")
            if name in vocabulary:
                vocab_used.append((where, name))

    if vocab_used:
        for side in VOCAB_SIDES:
            for where, name in vocab_used:
                if (side, name) not in vocab_have:
                    errors.append(f"{where}: {{{name}}} is used but the {side} vocabulary row taom_inc_voc_{side}_{name.lower()} is missing from this run")
    return sorted(set(errors))


def sort_key(row: dict) -> tuple:
    key = row["key"]
    if key.startswith(KEY_PREFIX + "voc_"):
        return (0, key, 0)
    match = SLOT.match(row["slot"])
    rank = 0 if row["slot"] == "title" else 1 if row["slot"] == "desc" else 1 + int(match.group(2)) if match else 99
    return (1, row["incident_id"] + "_" + row["side"], rank)


def variation_of(key: str) -> str:
    return key[len(KEY_PREFIX):]


def escape(value: str) -> str:
    return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def render_block(rows: list[dict], newline: str = "\n") -> str:
    """The generated block, markers included, one row per text, in a stable order."""
    lines = ["\t" + BEGIN]
    for row in sorted((r for r in rows if r["slot"] != "-"), key=sort_key):
        lines.append(f'\t<string id="{GAME_TEXT_ID}.{variation_of(row["key"])}" text="{{={row["key"]}}}{escape(row["text"])}" />')
    lines.append("\t" + END)
    return newline.join(lines)


def _block_span(xml_text: str) -> tuple[int, int] | None:
    """Where the generated block starts (its line) and ends (after the end marker); None when the file has none yet.
    The markers are found by prefix, so a reworded comment is still the same block."""
    begins, ends = xml_text.count(BEGIN_PREFIX), xml_text.count(END_PREFIX)
    if (begins, ends) == (0, 0):
        if ROW_ID.search(xml_text):
            raise ValueError(f"{GAME_TEXT_ID}.* rows stand outside the generated block's markers")
        return None
    if (begins, ends) != (1, 1):
        raise ValueError(f"expected one begin and one end marker, found {begins} and {ends}")
    start = xml_text.find(BEGIN_PREFIX)
    end = xml_text.find(END_PREFIX)
    if end < start:
        raise ValueError("the end marker comes before the begin marker")
    close = xml_text.find("-->", end)
    if close < 0:
        raise ValueError("the end marker is not a closed comment")
    span = (xml_text.rfind("\n", 0, start) + 1, close + len("-->"))
    if ROW_ID.search(xml_text[: span[0]]) or ROW_ID.search(xml_text[span[1]:]):
        raise ValueError(f"{GAME_TEXT_ID}.* rows stand outside the generated block's markers")
    return span


def block_ids(xml_text: str) -> set[str]:
    """The game-text ids the generated block holds now."""
    span = _block_span(xml_text)
    return set(ROW_ID.findall(xml_text[span[0]:span[1]])) if span else set()


def apply_block(xml_text: str, block: str) -> str:
    """Replaces the generated block, or adds it before </strings> on the first run. The rest of the file is untouched."""
    span = _block_span(xml_text)
    if span:
        return xml_text[: span[0]] + block + xml_text[span[1]:]
    close = xml_text.rfind("</strings>")
    if close < 0:
        raise ValueError("no </strings> in the XML file")
    newline = "\r\n" if "\r\n" in xml_text else "\n"
    return xml_text[:close] + block + newline + newline + xml_text[close:]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("drafts", nargs="*", type=Path, help="draft TSV files (default: every *.tsv in the drafts folder)")
    ap.add_argument("--catalog", type=Path, default=DEFAULT_CATALOG)
    ap.add_argument("--xml", type=Path, default=DEFAULT_XML, help="English strings file that holds the generated block")
    ap.add_argument("--apply", action="store_true", help="write the block (default: check only)")
    ap.add_argument("--allow-remove", action="store_true", help="let --apply drop shipped rows the drafts no longer hold")
    args = ap.parse_args(argv)
    try:
        return _run(args)
    except (OSError, ValueError) as error:
        print(error)
        return 2


def _run(args: argparse.Namespace) -> int:
    paths = args.drafts or sorted(DEFAULT_DRAFTS.glob("*.tsv"))
    if not paths:
        raise ValueError(f"no draft files given and none in {DEFAULT_DRAFTS}")
    catalog = load_catalog(args.catalog)
    rows = read_drafts(paths)
    errors = validate(rows, catalog)
    texts = [r for r in rows if r["slot"] != "-"]
    incidents = {r["incident_id"] for r in texts if not r["key"].startswith(KEY_PREFIX + "voc_")}
    print(f"{len(texts)} texts, {len(incidents)} incidents, {sum(1 for r in texts if r['key'].startswith(KEY_PREFIX + 'voc_'))} vocabulary rows")
    if errors:
        print(f"{len(errors)} problem(s):")
        for line in errors:
            print("  " + line)
        return 1
    if not args.apply:
        print("check only: pass --apply to write " + str(args.xml))
        return 0

    raw = args.xml.read_bytes().decode("utf-8")
    newline = "\r\n" if "\r\n" in raw else "\n"
    new = apply_block(raw, render_block(rows, newline))
    removed = sorted(block_ids(raw) - block_ids(new))
    print(f"the block held {len(block_ids(raw))} rows and will hold {len(block_ids(new))}")
    if removed and not args.allow_remove:
        print(f"refused: {len(removed)} shipped row(s) are not in these drafts (pass --allow-remove to drop them): " + ", ".join(removed[:10]) + (" ..." if len(removed) > 10 else ""))
        return 1
    try:
        ElementTree.fromstring(new.encode("utf-8"))
    except ElementTree.ParseError as error:
        print(f"refused: the result does not parse as XML ({error}); nothing written")
        return 1
    args.xml.write_bytes(new.encode("utf-8"))
    print("wrote the block into " + str(args.xml))
    return 0


if __name__ == "__main__":
    sys.exit(main())
